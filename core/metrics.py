# metrics.py
import time
from functools import wraps
from prometheus_client import start_http_server, Counter, Histogram

# 1. Define our Metrics
PROMPT_TOKENS = Counter('agent_prompt_tokens_total', 'Tokens sent TO the AI', ['agent_name'] )
COMPLETION_TOKENS = Counter('agent_completion_tokens_total', 'Tokens generated BY the AI', ['agent_name'])

# Latency for normal responses
AGENT_LATENCY = Histogram('agent_response_time_seconds', 'Time taken for agent to respond fully', ['agent_name'])
# NEW: Latency specifically for the start of streaming responses!
AGENT_TTFT = Histogram('agent_ttft_seconds', 'Time to First Token (Streaming)', ['agent_name'])

def start_agent_metrics_server(port=8001):
    try:
        start_http_server(port )
        print(f"📊 Agent Metrics Server running on port {port}...")
    except OSError:
        pass

def record_usage(agent_name, prompt_tokens, completion_tokens):
    if prompt_tokens:
        PROMPT_TOKENS.labels(agent_name=agent_name).inc(prompt_tokens)
    if completion_tokens:
        COMPLETION_TOKENS.labels(agent_name=agent_name).inc(completion_tokens)

# Decorator for standard (non-streaming) functions
def track_latency(func):
    @wraps(func)
    async def wrapper(agent_name, *args, **kwargs):
        start_time = time.time()
        result = await func(agent_name, *args, **kwargs) 
        AGENT_LATENCY.labels(agent_name=agent_name).observe(time.time() - start_time)
        return result
    return wrapper

# NEW: Decorator specifically for streaming functions!
def track_stream_latency(func):
    @wraps(func)
    async def wrapper(agent_name, *args, **kwargs):
        start_time = time.time()
        first_token_received = False
        
        # Loop through the stream generated by AI function
        async for chunk in func(agent_name, *args, **kwargs):
            # stop the TTFT timer after getting the first part of text
            if not first_token_received and chunk.strip():
                ttft_duration = time.time() - start_time
                AGENT_TTFT.labels(agent_name=agent_name).observe(ttft_duration)
                first_token_received = True
                
            yield chunk # Pass the text piece to the UI
            
    return wrapper
