from prometheus_client import start_http_server, Counter

# Define  Prometheus Token Counters
PROMPT_TOKENS = Counter('agent_prompt_tokens_total', 'Tokens sent TO the AI', ['agent_name'] )
COMPLETION_TOKENS = Counter('agent_completion_tokens_total', 'Tokens generated BY the AI', ['agent_name'])

def start_agent_metrics_server(port=8001):
    """Starts the Prometheus server safely."""
    try:
        start_http_server(port )
        print(f"Agent Metrics Server running on port {port}...")
    except OSError:
        # Ignore if the port is already bound (e.g., Streamlit auto-reloads)
        pass

def record_usage(agent_name, prompt_tokens, completion_tokens):
    """Helper function to record tokens safely."""
    if prompt_tokens:
        PROMPT_TOKENS.labels(agent_name=agent_name).inc(prompt_tokens)
    if completion_tokens:
        COMPLETION_TOKENS.labels(agent_name=agent_name).inc(completion_tokens)
